#!/usr/bin/env python3
"""Generate finite legal-domain inputs and MPFR interval-verified RNE oracles.

Limits follow the released corpus controls (not global error claims): f64 1,
logf 3 and expf 2 adjacent floating-point encoding steps from rounded MPFR.
Host MPFR is called directly; no Python math result is used as an oracle.
"""
import ctypes as C
import ctypes.util
import hashlib
import json
from pathlib import Path
import struct

FUNCS = ('log', 'exp', 'sin', 'cos', 'pow', 'logf', 'expf')
LIMITS = dict(log=1, exp=1, sin=1, cos=1, pow=1, logf=3, expf=2)
class MPFR(C.Structure):
    _fields_ = [('prec', C.c_long), ('sign', C.c_int), ('exp', C.c_long), ('d', C.c_void_p)]

def bits(x, single):
    return struct.unpack('<I' if single else '<Q', struct.pack('<f' if single else '<d', x))[0]

def rounded_input(x, single):
    return struct.unpack('<f', struct.pack('<f', x))[0] if single else x

def generate(out: Path):
    out.mkdir(parents=True, exist_ok=False)
    libname = ctypes.util.find_library('mpfr') or 'libmpfr.so.6'
    lib = C.CDLL(libname)
    ptr = C.POINTER(MPFR)
    lib.mpfr_get_version.restype = C.c_char_p
    lib.mpfr_init2.argtypes = [ptr, C.c_long]
    lib.mpfr_clear.argtypes = [ptr]
    lib.mpfr_set_d.argtypes = [ptr, C.c_double, C.c_int]
    lib.mpfr_get_d.argtypes = [ptr, C.c_int]; lib.mpfr_get_d.restype = C.c_double
    lib.mpfr_get_flt.argtypes = [ptr, C.c_int]; lib.mpfr_get_flt.restype = C.c_float
    for f in ('log', 'exp', 'sin', 'cos'):
        getattr(lib, 'mpfr_'+f).argtypes = [ptr, ptr, C.c_int]
    lib.mpfr_pow.argtypes = [ptr, ptr, ptr, C.c_int]
    a,b,lo,hi = [MPFR() for _ in range(4)]
    for v in (a,b,lo,hi): lib.mpfr_init2(C.byref(v), 512)
    info = {'oracle': 'MPFR directed interval endpoints rounded to RNE agree',
            'mpfr_version': lib.mpfr_get_version().decode(), 'library': libname,
            'precision_bits': 512, 'seed': 123456789, 'count_per_function': 1024,
            'limits_encoding_steps': LIMITS, 'functions': {}}
    try:
        for f in FUNCS:
            single = f.endswith('f'); base = f.removesuffix('f')
            state=123456789; xs=[]; ys=[]; refs=[]
            for i in range(1024):
                state=(state*6364136223846793005+1) & ((1<<64)-1)
                u=(state>>11)/9007199254740992.0
                state=(state*6364136223846793005+1) & ((1<<64)-1)
                v=(state>>11)/9007199254740992.0
                # Broad finite normal-domain inputs, deterministic binary values.
                x = (0.125+7.875*u) if base in ('log','pow') else (16*u-8 if base=='exp' else 64*u-32)
                y=4*v-2
                x,y=rounded_input(x,single),rounded_input(y,single)
                lib.mpfr_set_d(C.byref(a),x,0); lib.mpfr_set_d(C.byref(b),y,0)
                fn=getattr(lib,'mpfr_'+base)
                for dest,rnd in ((lo,3),(hi,2)): # RNDD/RNDU
                    args=[C.byref(dest),C.byref(a)] + ([C.byref(b)] if base=='pow' else []) + [rnd]
                    fn(*args)
                get=lib.mpfr_get_flt if single else lib.mpfr_get_d
                l,h=bits(get(C.byref(lo),0),single),bits(get(C.byref(hi),0),single)
                if l!=h: raise RuntimeError(f'ambiguous oracle interval {f} {i}: {l:x}/{h:x}')
                xs.append(bits(x,single)); ys.append(bits(y,single)); refs.append(l)
            typ='uint32_t' if single else 'uint64_t'; width=8 if single else 16
            lines=['/* Generated by generate_data.py: MPFR 512-bit directed intervals. */', '#include <stdint.h>',
                   f'#define ORACLE_LIMIT {LIMITS[f]}', '#define DATA_COUNT 1024']
            for name,values in [('input_bits',xs),('second_bits',ys),('reference_bits',refs)]:
                lines.append(f'static const {typ} {name}[DATA_COUNT] = {{')
                for start in range(0,len(values),4):
                    lines.append('  '+', '.join(f'0x{x:0{width}x}'+('U' if single else 'ULL') for x in values[start:start+4])+',')
                lines.append('};')
            text='\n'.join(lines)+'\n'; path=out/(f+'.h'); path.write_text(text)
            info['functions'][f]={'header':path.name,'sha256':hashlib.sha256(text.encode()).hexdigest(),
                'domain':'x in [0.125,8), y in [-2,2)' if base=='pow' else ('x in [0.125,8)' if base=='log' else 'x in [-8,8)' if base=='exp' else 'x in [-32,32)'), 'interval_agreement':1024}
    finally:
        for v in (a,b,lo,hi): lib.mpfr_clear(C.byref(v))
    (out/'oracle.json').write_text(json.dumps(info,indent=2)+'\n')
    return info

if __name__=='__main__':
    import argparse
    p=argparse.ArgumentParser(description=__doc__); p.add_argument('output',type=Path)
    generate(p.parse_args().output)
